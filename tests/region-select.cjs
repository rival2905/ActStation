const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const assert = require('node:assert/strict');
const source = fs.readFileSync(path.join(__dirname, '../resources/views/components/region-select.blade.php'),'utf8');
let script = source.match(/<script>([\s\S]*?)<\/script>/)[1].replace(/@json\([^\n]*\)/g, '""');
const ids = ['province','city','district','village','postal_code'];
const els = Object.fromEntries(ids.map(id => [id, {value:'',disabled:false,options:[],handlers:{},getAttribute(){return 'Choose';},addEventListener(k,f){this.handlers[k]=f;},appendChild(o){this.options.push(o);},set innerHTML(v){this.options=[];}}]));
const root = {querySelector(s){return els[s.match(/"(.*?)"/)[1]];},dispatchEvent(){}};
const pending=[];
const context={document:{getElementById(id){return id.includes('load_error')||id.includes('postal_load_error') ? null : root;}},console,Option:function(text,value){this.text=text;this.value=value;},CustomEvent:function(){},fetch(url){return new Promise(resolve=>pending.push({url,resolve}));}};
vm.runInNewContext(script,context);
const flush=()=>new Promise(resolve=>setImmediate(resolve));
const respond=(p,data)=>p.resolve({ok:true,json:()=>Promise.resolve(data)});
(async()=>{
 respond(pending.shift(),[]); await flush();
 els.province.value='32';els.province.handlers.change.call(els.province);
 respond(pending.shift(),[{kode:'32.73',nama:'Bandung'}]);await flush();
 els.city.value='32.73';els.city.handlers.change.call(els.city);
 const oldDistrict=pending.shift();
 els.province.value='';els.province.handlers.change.call(els.province);
 respond(oldDistrict,[{kode:'32.73.01',nama:'Old district'}]);await flush();
 assert.equal(els.district.disabled,true,'Old response must not enable district after province cleared');
 assert.equal(els.district.options.length,1,'Stale district data rejected');
 els.village.value='32.73.01.1001';els.village.handlers.change.call(els.village);
 const oldPostal=pending.shift();
 els.village.value='';els.village.handlers.change.call(els.village);
 respond(oldPostal,{kodepos:'40151'});await flush();
 assert.equal(els.postal_code.value,'','Old postcode response ignored after village cleared');
 console.log('PASS: cascading parent reset and stale postcode response');
})().catch(e=>{console.error(e.message);process.exitCode=1;});
